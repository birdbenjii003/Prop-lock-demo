'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('scripts/deep-dive-snaps.js','utf8');
const app=vm.runInNewContext(src+'\n({deepDiveParseVerifiedSnapCsv,deepDiveMatchedSnaps,deepDiveSnapSummary})');
const header='player_id,season,week,team,offense_snaps,offense_pct';
const csvRows=['ID1,2023,1,A,55,0.8','ID1,2023,2,A,51,0.75','ID2,2024,2,A,4,0.1'];
const parse=raw=>raw.trim().split('\n').map(line=>line.split(','));
const rows=Array.from({length:500},(_,i)=>`GSIS${i},2023,1,A,51,0.75`);
rows[0]='ID1,2023,1,A,55,0.8';rows[1]='ID1,2023,2,A,51,0.75';
const all=app.deepDiveParseVerifiedSnapCsv(header+'\n'+rows.join('\n')+'\n',parse);
assert.equal(all.length,500);
const p={source:'imported',playerKey:'id:ID1',records:[{season:2023,week:1,team:'A'},{season:2023,week:2,team:'A'}]};
const metrics=app.deepDiveSnapSummary(p,all);
assert.equal(metrics.matched,2);assert.equal(metrics.avgSnaps,53);
assert.ok(Math.abs(metrics.avgPct-.775)<.000001);
assert.equal(app.deepDiveMatchedSnaps({...p,playerKey:'name:ID1'},all).length,0);
assert.equal(app.deepDiveMatchedSnaps({...p,records:[{season:2023,week:1,team:'B'}]},all).length,0);
assert.throws(()=>app.deepDiveParseVerifiedSnapCsv(header+'\n'+[...rows,'ID1,2023,1,A,51,0.7'].join('\n'),parse),/Duplicate/);
assert.throws(()=>app.deepDiveParseVerifiedSnapCsv(header+'\n'+rows.slice(0,2).join('\n'),parse),/500/);
console.log('Verified snap parser and joins: PASS');
