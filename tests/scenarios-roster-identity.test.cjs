'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const api=vm.runInNewContext(fs.readFileSync('scripts/scenarios-roster-identity.js','utf8')+'\n({scenarioRosterUrl,scenarioNormalizePersonName,scenarioRosterCandidates,scenarioCheckRoster,scenarioRosterIsFresh,scenarioPlayerGameGate})',{Date});
const now=Date.parse('2026-11-23T12:00:00Z');
const player={name:'Example Player Jr.',team:'ATL',position:'RB',playerKey:'gsis:example'};
const roster=entries=>({athletes:[{position:'Offense',items:entries}]});
const one=api.scenarioCheckRoster(roster([{id:'espn-100',fullName:'Example Player',position:{abbreviation:'RB'}}]),player,'ATL',now);
assert.equal(one.status,'PROVISIONAL_NAME_MATCH');
assert.equal(api.scenarioPlayerGameGate(one,player,'ATL',now).status,'PROVISIONAL_ONLY');
assert.equal(api.scenarioPlayerGameGate(one,player,'ATL',now+7*3600000).status,'ROSTER_UNVERIFIED');
assert.equal(api.scenarioPlayerGameGate(one,player,'NYJ',now).status,'TEAM_MISMATCH');
assert.equal(api.scenarioCheckRoster(roster([]),player,'ATL',now).status,'ROSTER_EMPTY');
assert.equal(api.scenarioCheckRoster(roster([{fullName:'Different Player'}]),player,'ATL',now).status,'NOT_FOUND_ON_TEAM_ROSTER');
assert.equal(api.scenarioCheckRoster(roster([{fullName:'Example Player'},{fullName:'Example Player Jr.'}]),player,'ATL',now).status,'AMBIGUOUS_NAME_MATCH');
assert.equal(api.scenarioCheckRoster(roster([{fullName:'Example Player',position:{abbreviation:'WR'}}]),player,'ATL',now).status,'POSITION_CONFLICT');
assert.equal(api.scenarioCheckRoster({athletes:null},player,'ATL',now).status,'ROSTER_UNAVAILABLE');
assert.equal(api.scenarioCheckRoster(roster([{fullName:'Example Player',position:{abbreviation:'RB'}}]),player,'ATL',now).status,'PROVISIONAL_NAME_MATCH');
assert.equal(api.scenarioPlayerGameGate({...one,matchedName:'Other Player'},player,'ATL',now).status,'PLAYER_TEAM_NOT_CONFIRMED');
assert.equal(api.scenarioRosterUrl('A T L'),null);
assert.ok(api.scenarioRosterUrl('ATL').includes('/teams/atl/roster'));
assert.equal(api.scenarioNormalizePersonName('JOSÉ O’NEILL III'),api.scenarioNormalizePersonName('Jose ONeill'));
console.log('Roster gate checks PASS: name collisions, position mismatch, unmatched, stale and team mismatch');
console.log('No cross-provider player ID join is established by these tests.');
